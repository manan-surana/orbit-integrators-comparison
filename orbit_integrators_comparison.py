import numpy as np
import matplotlib.pyplot as plt

GM = 1.0  # units where GM = 1 and orbit radius = 1 (one orbit takes 2*pi time)

def accel(r):
    return -GM * r / np.linalg.norm(r)**3

def energy(r, v):
    return 0.5 * np.dot(v, v) - GM / np.linalg.norm(r)

def euler_step(r, v, dt):
    a = accel(r)
    return r + v*dt, v + a*dt

def rk4_step(r, v, dt):
    k1r = v
    k1v = accel(r)
    k2r = v + 0.5*dt*k1v
    k2v = accel(r + 0.5*dt*k1r)
    k3r = v + 0.5*dt*k2v
    k3v = accel(r + 0.5*dt*k2r)
    k4r = v + dt*k3v
    k4v = accel(r + dt*k3r)
    r_new = r + dt/6 * (k1r + 2*k2r + 2*k3r + k4r)
    v_new = v + dt/6 * (k1v + 2*k2v + 2*k3v + k4v)
    return r_new, v_new

def run(step, dt, n_orbits=10):
    n_steps = int(n_orbits * 2*np.pi / dt)
    r = np.array([1.0, 0.0])   # start position
    v = np.array([0.0, 1.0])   # circular-orbit speed
    E0 = energy(r, v)
    xs, ys, err = [], [], []
    for _ in range(n_steps):
        r, v = step(r, v, dt)
        xs.append(r[0]); ys.append(r[1])
        err.append(abs((energy(r, v) - E0) / E0))
    return np.array(xs), np.array(ys), np.array(err)

# Plot 1: orbit shape and energy error over time
dt = 0.01
xe, ye, ee = run(euler_step, dt)
xr, yr, er = run(rk4_step, dt)

fig, ax = plt.subplots(1, 2, figsize=(11, 4.5))
ax[0].plot(xe, ye, label="Euler", lw=0.8)
