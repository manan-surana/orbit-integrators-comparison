import numpy as np
from scipy.integrate import solve_ivp
GM = 1.0
def accel(r): return -GM * r / np.linalg.norm(r)**3

def explicit_euler(r, v, dt):
    return r + v*dt, v + accel(r)*dt
def semi_implicit_euler(r, v, dt):
    v_new = v + accel(r)*dt
    return r + v_new*dt, v_new
def rk4_step(r, v, dt):
    k1r=v; k1v=accel(r)
    k2r=v+0.5*dt*k1v; k2v=accel(r+0.5*dt*k1r)
    k3r=v+0.5*dt*k2v; k3v=accel(r+0.5*dt*k2r)
    k4r=v+dt*k3v;     k4v=accel(r+dt*k3r)
    return (r+dt/6*(k1r+2*k2r+2*k3r+k4r), v+dt/6*(k1v+2*k2v+2*k3v+k4v))
def leapfrog(r, v, dt):
    vh = v + 0.5*dt*accel(r); rn = r + dt*vh
    return rn, vh + 0.5*dt*accel(rn)

dt = 0.01; n = int(10*2*np.pi/dt)
times = dt*np.arange(1, n+1)
def rhs(t, y): return np.concatenate([y[2:], accel(y[:2])])
ref = solve_ivp(rhs, [0, times[-1]], [1,0,0,1], method="DOP853",
                rtol=1e-12, atol=1e-12, t_eval=times).y[:2].T

def path(step):
    r = np.array([1.0,0.0]); v = np.array([0.0,1.0]); out=[]
    for _ in range(n):
        r, v = step(r, v, dt); out.append(r.copy())
    return np.array(out)

def ang_mom_err(step):
    r = np.array([1.0,0.0]); v = np.array([0.0,1.0])
    for _ in range(n):
        r, v = step(r, v, dt)
    return abs(r[0]*v[1]-r[1]*v[0]-1.0)

for name, f in [("explicit Euler", explicit_euler), ("semi-implicit Euler", semi_implicit_euler),
                ("RK4", rk4_step), ("leapfrog", leapfrog)]:
    d = np.linalg.norm(path(f)-ref, axis=1)
    print(f"{name:20s} max position diff vs solve_ivp: {d.max():.2e}   angular-momentum error: {ang_mom_err(f):.2e}")